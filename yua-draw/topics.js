  const l = (x1, y1, x2, y2, p) => ({ t: 'l', x1, y1, x2, y2, p });
  const pl = (pts, closed, p) => ({ t: 'p', pts: pts, closed: !!closed, p });
  const a = (cx, cy, r, a0, a1, p) => ({ t: 'a', cx, cy, r, a0, a1, p });

  // 중심에서 바깥으로 뻗는 햇살/짧은 선들
  function rays(cx, cy, r1, r2, n, rotDeg, p) {
    const out = [];
    for (let i = 0; i < n; i++) {
      const ang = ((rotDeg + (i * 360) / n) * Math.PI) / 180;
      out.push(l(
        cx + Math.cos(ang) * r1, cy + Math.sin(ang) * r1,
        cx + Math.cos(ang) * r2, cy + Math.sin(ang) * r2, p
      ));
    }
    return out;
  }

  // 둘레에 작은 원(꽃잎·펫털)을 배치
  function ring(cx, cy, radius, count, r, startDeg, p, squish) {
    const out = [];
    for (let i = 0; i < count; i++) {
      const ang = ((startDeg + (i * 360) / count) * Math.PI) / 180;
      const px = cx + Math.cos(ang) * radius;
      const py = cy + Math.sin(ang) * radius;
      if (squish) {
        out.push(e(px, py, r, squash(r, squish), (ang * 180) / Math.PI + 90, p));
      } else {
        out.push(c(px, py, r, p));
      }
    }
    return out;
  }
  const squash = (r, k) => r * k;

